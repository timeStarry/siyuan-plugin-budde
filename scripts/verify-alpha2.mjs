import { chromium, expect } from "@playwright/test";
import { mkdir, writeFile } from "node:fs/promises";
import { startPreview } from "./preview.mjs";

const preview = await startPreview();
const browser = await chromium.launch({ channel: "msedge", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: "reduce" });
const errors = [], passed = [];
page.on("pageerror", error => errors.push(error.message));
const part = name => page.locator(`[data-part="${name}"]`);
const editor = name => page.locator(`[data-editor-field="${name}"]`);
const setting = name => page.locator(`[data-settings-action="${name}"]`);
const snapshot = () => page.evaluate(() => window.buddeTest.client.snapshot());
const globalMenu = async () => { await page.locator('.header-secondary [data-menu-trigger]').click(); return page.getByRole('menu'); };
const closeSettings = async () => { await setting('close').click(); await expect(part('settings-dialog')).not.toBeVisible(); };
const saveSettings = async () => { await part('settings-form').getByRole('button', { name: '保存设置', exact: true }).click(); await expect(part('settings-form')).toHaveCount(0); };
try {
  await page.goto(preview.url); await expect(part('capture-title')).toBeEnabled();
  const menu = await globalMenu();
  await expect(menu.getByRole('menuitem')).toHaveCount(2);
  await expect(menu).toContainText('导出 JSON'); await expect(menu).toContainText('重新读取');
  await page.keyboard.press('Escape');
  await page.locator('[data-view="board"]').click();
  await part('type-index').locator('[data-action="type.create"]').click();
  await expect(part('settings-form')).toBeVisible();
  await expect(editor('name')).toBeFocused();
  await editor('name').fill('离线资料库');
  const picker = page.locator('[data-type-picker]');
  await expect(picker.locator('[data-icon-option]')).toHaveCount(36);
  await picker.getByRole('searchbox', { name: '搜索图标' }).fill('书籍');
  await picker.getByRole('searchbox', { name: '搜索图标' }).press('Enter');
  await expect(part('settings-form')).toBeVisible();
  await expect(picker.locator('[data-icon-option]')).toHaveCount(1);
  await picker.getByRole('button', { name: '阅读', exact: true }).click();
  await picker.getByRole('button', { name: '青绿', exact: true }).click();
  await expect(picker.locator('[data-type-preview]')).toContainText('离线资料库');
  await expect(picker.locator('[data-type-preview]')).toHaveAttribute('data-color', 'emerald');
  await editor('template').selectOption('article');
  await saveSettings();
  let state = await snapshot(), type = state.types.at(-1);
  expect(type.icon).toBe('BookOpen'); expect(type.color).toBe('emerald');
  expect(type.stages.map(s => s.name)).toEqual(['选题', '写作', '修改', '已发布']);
  await closeSettings();
  const row = part('type-index').locator(`[data-type-row="${type.id}"]`);
  await row.locator('[data-type]').click();
  await row.hover(); await row.locator('[data-action="type.settings"]').click();
  await expect(editor('name')).toHaveValue('离线资料库');
  await page.getByRole('tab', { name: 'Emoji', exact: true }).click();
  await page.getByRole('textbox', { name: '单个 Emoji' }).fill('👩🏽‍💻');
  await page.getByRole('textbox', { name: '单个 Emoji' }).press('Enter');
  await expect(part('settings-form')).toBeVisible();
  await page.getByRole('button', { name: '使用 Emoji', exact: true }).click();
  await setting('close').click(); await page.locator('[data-choice="cancel"]').click();
  await expect(page.getByRole('textbox', { name: '单个 Emoji' })).toHaveValue('👩🏽‍💻');
  await page.evaluate(() => { const client = window.buddeTest.client, execute = client.execute.bind(client); client.execute = async () => { client.execute = execute; throw Error('合成外观保存失败'); }; });
  await part('settings-form').getByRole('button', { name: '保存设置', exact: true }).click();
  await expect(part('settings-error')).toContainText('合成外观保存失败');
  await expect(page.getByRole('textbox', { name: '单个 Emoji' })).toHaveValue('👩🏽‍💻');
  await expect(picker.locator('[data-type-preview]')).toContainText('👩🏽‍💻');
  await saveSettings(); await closeSettings();
  state = await snapshot(); type = state.types.at(-1); expect(type.icon).toBe('👩🏽‍💻');
  await expect(row.locator('[data-type]')).toContainText('👩🏽‍💻');
  passed.push('global menu is restricted; contextual creation, 36 offline icons, Chinese filter, colors, live preview, templates and Emoji persist');

  const ghost = page.locator('[data-ghost-column]');
  await ghost.getByRole('button', { name: '新增阶段', exact: true }).click();
  const stageInput = ghost.getByRole('textbox', { name: '新阶段名称' });
  await expect(stageInput).toBeFocused(); await stageInput.fill('资料归档与长期维护');
  await stageInput.dispatchEvent('compositionstart');
  await stageInput.press('Enter');
  expect((await snapshot()).types.at(-1).stages).toHaveLength(4);
  await page.evaluate(() => { const client = window.buddeTest.client, execute = client.execute.bind(client); window.alphaExecute = execute; window.alphaCalls = 0; client.execute = async command => { window.alphaCalls++; await new Promise(resolve => window.alphaRelease = resolve); return execute(command); }; });
  await stageInput.dispatchEvent('compositionend'); await stageInput.press('Enter');
  await expect(ghost.locator('form')).toHaveAttribute('aria-busy', 'true');
  await page.evaluate(() => { const form = document.querySelector('[data-ghost-column] form'); form.requestSubmit(); form.requestSubmit(); });
  expect(await page.evaluate(() => window.alphaCalls)).toBe(1);
  await page.evaluate(() => { window.buddeTest.client.execute = window.alphaExecute; window.alphaRelease(); });
  await expect(ghost.getByRole('button', { name: '新增阶段', exact: true })).toBeVisible();
  state = await snapshot(); type = state.types.at(-1); const added = type.stages.at(-1);
  expect(added.name).toBe('资料归档与长期维护');
  expect(added.completed).toBe(false);
  await page.evaluate(() => {
    const client = window.buddeTest.client, execute = client.execute.bind(client);
    window.alphaExecute = execute;
    client.execute = async command => { if (command.kind === 'stage.add') throw Error('合成阶段保存失败'); return execute(command); };
  });
  await ghost.getByRole('button', { name: '新增阶段', exact: true }).click();
  await stageInput.fill('失败后保留'); await stageInput.press('Enter');
  await expect(stageInput).toHaveValue('失败后保留');
  await expect(ghost.getByRole('alert')).toContainText('合成阶段保存失败');
  expect((await snapshot()).types.at(-1).stages).toHaveLength(5);
  await page.evaluate(async () => { const client = window.buddeTest.client; client.execute = window.alphaExecute; const state = await client.snapshot(), type = state.types.at(-1); await client.execute({ kind: 'type.update', id: type.id, name: type.name, expectedRevision: state.revision }); });
  await stageInput.press('Enter'); await expect(ghost.getByRole('alert')).toContainText('版本');
  await expect(stageInput).toHaveValue('失败后保留');
  await globalMenu(); await page.getByRole('menu').locator('[data-action="refresh"]').click();
  await expect(stageInput).toHaveValue('失败后保留');
  await stageInput.press('Escape'); await expect(stageInput).toHaveCount(0);
  passed.push('Ghost Column guards IME and duplicates; failures/conflicts and explicit reload retain input; Escape cancels');

  const column = page.locator(`[data-stage-id="${added.id}"]`);
  await column.hover(); await column.locator('[data-menu-trigger]').click();
  await page.getByRole('menu').getByRole('menuitem', { name: '重命名阶段', exact: true }).click();
  await expect(editor('name')).toHaveValue(added.name);
  await editor('name').fill('维护与复查'); await saveSettings(); await closeSettings();
  await column.hover(); await column.locator('[data-menu-trigger]').click();
  await page.getByRole('menu').getByRole('menuitem', { name: '标记为完成阶段', exact: true }).click();
  await expect.poll(async () => (await snapshot()).types.at(-1).stages.at(-1).completed).toBe(true);
  await column.hover(); await column.locator('[data-menu-trigger]').click();
  await page.getByRole('menu').getByRole('menuitem', { name: '向左移动', exact: true }).click();
  await expect.poll(async () => (await snapshot()).types.at(-1).stages.at(-2).id).toBe(added.id);
  // A stage migration must include archived items and preserve their archive state.
  await page.evaluate(async ({ typeId, stageId }) => {
    const client = window.buddeTest.client;
    const created = await client.execute({ kind: 'item.create', requestId: 'alpha2-archived', title: '合成归档迁移', typeId });
    const item = created.state.items.find(i => i.id === created.itemId);
    await client.execute({ kind: 'item.update', id: item.id, expectedVersion: item.version, patch: { stageId, archived: true } });
    await window.buddeTest.view.refresh();
  }, { typeId: type.id, stageId: added.id });
  await column.hover(); await column.locator('[data-menu-trigger]').click();
  await page.getByRole('menu').getByRole('menuitem', { name: '删除并迁移', exact: true }).click();
  await expect(part('migration-impact')).toContainText('其中 1 个归档');
  await editor('targetId').selectOption(type.stages[0].id);
  await part('settings-form').getByRole('button', { name: '确认删除并迁移', exact: true }).click();
  await expect(part('settings-form')).toHaveCount(0); await closeSettings();
  state = await snapshot(); const migrated = state.items.find(i => i.title === '合成归档迁移');
  expect(migrated.archived).toBe(true); expect(migrated.stageId).toBe(type.stages[0].id); expect(migrated.version).toBe(3);
  passed.push('column menus rename, toggle completion, reorder and safely migrate archived items');

  expect(errors).toEqual([]);
  await mkdir('artifacts/qa', { recursive: true });
  await writeFile('artifacts/qa/alpha2-results.json', JSON.stringify({ passed, errors }, null, 2));
  console.log(`${passed.length} alpha.2 interaction groups passed`);
} finally { await browser.close(); await preview.close(); }
